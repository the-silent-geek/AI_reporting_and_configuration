"""Settings, read once at startup.

Two env files, both git-ignored:
  db/.env       generated by db/build.ps1 -> DB host/port/name + passwords of the 7 DB roles
  backend/.env  backend secrets/options (copy backend/.env.example)
Real environment variables override both.
"""
import os
from dataclasses import dataclass
from pathlib import Path

from dotenv import load_dotenv

ROOT = Path(__file__).resolve().parents[2]
load_dotenv(ROOT / "backend" / ".env")
load_dotenv(ROOT / "db" / ".env")

PRODUCTS = ("erp", "aml", "lending")  # schema names == lower-case app codes


def _req(name: str) -> str:
    value = os.getenv(name)
    if not value:
        raise RuntimeError(f"Missing setting {name} (see backend/.env.example and db/build.ps1)")
    return value


@dataclass(frozen=True)
class Settings:
    db_host: str
    db_port: int
    db_name: str
    role_passwords: dict[str, str]   # db role -> password
    jwt_secret: str
    access_token_minutes: int
    cookie_secure: bool
    cors_origins: list[str]
    rabbitmq_url: str                # empty -> local in-process broker (dev/tests)
    storage_dir: Path
    max_upload_mb: int
    dev_endpoints: bool              # enables /dev/* helpers (fake worker progress)

    def dsn(self, role: str) -> str:
        return (f"host={self.db_host} port={self.db_port} dbname={self.db_name} "
                f"user={role} password={self.role_passwords[role]}")


def load() -> Settings:
    roles = ["iam_app", *(f"{p}_app" for p in PRODUCTS)]
    return Settings(
        db_host=os.getenv("DB_HOST", "localhost"),
        db_port=int(os.getenv("DB_PORT", "5432")),
        db_name=os.getenv("DB_NAME", "reporting_studio"),
        role_passwords={r: _req(f"{r.upper()}_PASSWORD") for r in roles},
        jwt_secret=_req("JWT_SECRET"),
        access_token_minutes=int(os.getenv("ACCESS_TOKEN_MINUTES", "15")),
        cookie_secure=os.getenv("COOKIE_SECURE", "false").lower() == "true",
        cors_origins=[o for o in os.getenv("CORS_ORIGINS", "http://localhost:5173").split(",") if o],
        rabbitmq_url=os.getenv("RABBITMQ_URL", ""),
        # empty value in .env = default; always absolute (stored as file:// URI for the worker)
        storage_dir=Path(os.getenv("STORAGE_DIR") or ROOT / "backend" / "storage").resolve(),
        max_upload_mb=int(os.getenv("MAX_UPLOAD_MB", "50")),
        dev_endpoints=os.getenv("DEV_ENDPOINTS", "false").lower() == "true",
    )


settings = load()
