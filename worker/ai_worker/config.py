"""Worker settings, read once at startup.

Env files, all git-ignored, first one wins per variable:
  worker/.env   worker-only options (copy worker/.env.example)
  backend/.env  shared RABBITMQ_URL / STORAGE_DIR, so API and worker can't disagree
  db/.env       generated by db/build.ps1 -> DB host/port/name + <product>_APP_PASSWORD
Real environment variables override all of them.
"""
import os
from dataclasses import dataclass
from pathlib import Path

from dotenv import load_dotenv

ROOT = Path(__file__).resolve().parents[2]
load_dotenv(ROOT / "worker" / ".env")
load_dotenv(ROOT / "backend" / ".env")
load_dotenv(ROOT / "db" / ".env")

PRODUCTS = ("erp", "aml", "lending")  # schema names == lower-case app codes


def _req(name: str) -> str:
    value = os.getenv(name)
    if not value:
        raise RuntimeError(f"Missing setting {name} (see worker/.env.example and db/build.ps1)")
    return value


def _float(name: str, default: float) -> float:
    return float(os.getenv(name) or default)


def _int(name: str, default: int) -> int:
    return int(os.getenv(name) or default)


@dataclass(frozen=True)
class Settings:
    db_host: str
    db_port: int
    db_name: str
    role_passwords: dict[str, str]   # <product>_app -> password (the worker never uses iam_app)
    rabbitmq_url: str
    storage_dir: Path                # only files under here may be read
    concurrency: int                 # jobs processed at the same time (= RabbitMQ prefetch)
    max_attempts: int                # temporary failures are retried this many times in total
    retry_base_seconds: float
    # mapping
    embedding_model: str             # empty -> BGE layer off
    bge_accept: float                # BGE cosine needed to accept without Groq
    bge_margin: float                # ... and lead over the runner-up
    groq_api_key: str                # empty -> Groq layer off, ambiguous fields left for review
    groq_model: str
    groq_base_url: str
    groq_timeout_seconds: float
    # PDF / OCR
    pdf_min_text_chars: int          # fewer embedded chars on a page -> treat page as scanned
    ocr_dpi: int
    ocr_lang: str
    ocr_review_below: float          # OCR rows under this confidence -> NEEDS_REVIEW
    ocr_timeout_seconds: float       # whole-document OCR budget

    def dsn(self, app: str) -> str:
        role = f"{app}_app"
        return (f"host={self.db_host} port={self.db_port} dbname={self.db_name} "
                f"user={role} password={self.role_passwords[role]}")


def load() -> Settings:
    return Settings(
        db_host=os.getenv("DB_HOST", "localhost"),
        db_port=_int("DB_PORT", 5432),
        db_name=os.getenv("DB_NAME", "reporting_studio"),
        role_passwords={f"{p}_app": os.getenv(f"{p.upper()}_APP_PASSWORD", "") for p in PRODUCTS},
        rabbitmq_url=os.getenv("RABBITMQ_URL", ""),
        storage_dir=Path(os.getenv("STORAGE_DIR") or ROOT / "backend" / "storage").resolve(),
        concurrency=_int("WORKER_CONCURRENCY", 1),
        max_attempts=_int("WORKER_MAX_ATTEMPTS", 3),
        retry_base_seconds=_float("WORKER_RETRY_BASE_SECONDS", 5),
        embedding_model=os.getenv("EMBEDDING_MODEL", "BAAI/bge-small-en-v1.5"),
        bge_accept=_float("BGE_ACCEPT", 0.80),
        bge_margin=_float("BGE_MARGIN", 0.03),
        groq_api_key=os.getenv("GROQ_API_KEY", ""),
        # Llama models are no longer offered on Groq; free tier for this one: 8k tokens/min, 200k/day
        groq_model=os.getenv("GROQ_MODEL", "openai/gpt-oss-120b"),
        groq_base_url=os.getenv("GROQ_BASE_URL", "https://api.groq.com/openai/v1"),
        groq_timeout_seconds=_float("GROQ_TIMEOUT_SECONDS", 20),
        pdf_min_text_chars=_int("PDF_MIN_TEXT_CHARS", 20),
        ocr_dpi=_int("OCR_DPI", 200),
        ocr_lang=os.getenv("OCR_LANG", "en"),
        ocr_review_below=_float("OCR_REVIEW_BELOW", 0.80),
        ocr_timeout_seconds=_float("OCR_TIMEOUT_SECONDS", 600),
    )


def check_runtime(s: Settings) -> None:
    """Settings that only the running worker needs (tests build Settings without them)."""
    if not s.rabbitmq_url:
        raise RuntimeError("Missing setting RABBITMQ_URL (the worker has no in-process broker)")
    for role, pw in s.role_passwords.items():
        if not pw:
            _req(f"{role.upper()}_PASSWORD")


settings = load()
